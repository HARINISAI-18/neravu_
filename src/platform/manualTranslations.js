export const manualTranslations = Object.fromEntries(
  Object.entries(landingValues).map(([language, values]) => {
    if (values.length !== landingKeys.length) {
      throw new Error(`Manual ${language} landing translations do not match the English key count.`);
    }
    if (sharedValues[language]?.length !== sharedKeys.length) {
      throw new Error(`Manual ${language} shared translations do not match the English key count.`);
    }
    if (ngoValues[language]?.length !== ngoKeys.length) {
      throw new Error(`Manual ${language} NGO translations do not match the English key count.`);
    }
    return [language, {
      ...Object.fromEntries(landingKeys.map((key, index) => [key, values[index]])),
      ...Object.fromEntries(sharedKeys.map((key, index) => [key, sharedValues[language][index]])),
      ...Object.fromEntries(ngoKeys.map((key, index) => [key, ngoValues[language][index]]))
    }];
  })
);
