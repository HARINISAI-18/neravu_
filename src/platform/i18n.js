function getCatalog(language) {
  return {
    ...translations[language],
    ...generatedTranslations[language],
    ...intakeTranslations[language],
    ...landingTranslations[language],
    ...manualTranslations[language],
    ...infoPageTranslations[language]
  };
}

export function translate(language, key, values = {}) {
  let text = getCatalog(language)[key]
    ?? translations.en[key]
    ?? key;
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}


export function translateOption(language, option) {
  return getCatalog(language)[`option.${option}`] ?? translations.en[`option.${option}`] ?? option;
}
